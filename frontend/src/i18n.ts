export type Key = keyof typeof TR

let cur: Lang = (() => { try { return typeof localStorage !== 'undefined' && localStorage.getItem(KEY) === 'tr' ? 'tr' : 'en' } catch { return 'en' } })()
export const getLang = () => cur

const TR_MONTHS = ['Ocak', 'Şubat', 'Mart', 'Nisan', 'Mayıs', 'Haziran', 'Temmuz', 'Ağustos', 'Eylül', 'Ekim', 'Kasım', 'Aralık']
const TR_DAYS = ['Pazar', 'Pazartesi', 'Salı', 'Çarşamba', 'Perşembe', 'Cuma', 'Cumartesi']
const EN_DAYS = ['Sunday', 'Monday', 'Tuesday', 'Wednesday', 'Thursday', 'Friday', 'Saturday']
/** Weekday names in the interface language, Sunday first. */
export const dayName = (i: number) => (cur === 'tr' ? TR_DAYS : EN_DAYS)[i]
// Turkish weekdays can't be cut to three letters: Pazartesi and Pazar would both read "Paz"
const TR_DAYS_SHORT = ['Paz', 'Pzt', 'Sal', 'Çar', 'Per', 'Cum', 'Cmt']
/** Short weekday names in the interface language, Sunday first. */
export const dayShort = (i: number) => (cur === 'tr' ? TR_DAYS_SHORT[i] : EN_DAYS[i].slice(0, 3))
const EN_MONTHS = ['January', 'February', 'March', 'April', 'May', 'June', 'July', 'August', 'September', 'October', 'November', 'December']
/** Month names in the interface language. The array is shared (other modules index it), so it is refilled in place. */
export const MONTHS: string[] = [...(cur === 'tr' ? TR_MONTHS : EN_MONTHS)]

export function t(k: Key, v?: Record<string, string | number>): string {
  let s: string = cur === 'tr' ? TR[k] : k
  if (v) for (const [a, b] of Object.entries(v)) s = s.split(`{${a}}`).join(String(b))
  return s
}

/** A string that may or may not be one of ours (a stored label, a block name from the plan): translated when the
    dictionary knows it, shown as it is otherwise. */
export const tx = (s: string): string => (cur === 'tr' && Object.hasOwn(TR, s) ? TR[s as Key] : s)
/** Hours and minutes in the interface language: "2 h 15 min" / "2 sa 15 dk". */
export const unit = () => (cur === 'tr' ? { h: 'sa', m: 'dk', d: 'gün' } : { h: 'h', m: 'min', d: 'd' })

/** "Nov 23" in English, "23 Kas" in Turkish. */
export const fmtDay = (m: number, d: number) => (cur === 'tr' ? `${d} ${MONTHS[m - 1].slice(0, 3)}` : `${MONTHS[m - 1].slice(0, 3)} ${d}`)

function apply(l: Lang) {
  cur = l
  MONTHS.splice(0, 12, ...(l === 'tr' ? TR_MONTHS : EN_MONTHS))
  if (typeof document !== 'undefined') document.documentElement.lang = l
}
apply(cur)

/** The language and its setter. Changing it re-renders the app from the top, so every t() call reads the new one. */
export function useLang(): [Lang, (l: Lang) => void] {
  const [l, setL] = useState<Lang>(cur)
  const set = useCallback((n: Lang) => {
    try { localStorage.setItem(KEY, n) } catch { /* private mode: still applies for this visit */ }
    apply(n)
    setL(n)
  }, [])
  return [l, set]
}
